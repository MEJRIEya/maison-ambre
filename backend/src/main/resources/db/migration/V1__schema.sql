-- Maison Ambre schema.
-- Money is NUMERIC(12,2) (exact decimal, never float) and always travels with an ISO 4217 currency code.

-- A boutique sells in one local currency.
CREATE TABLE boutique (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code     VARCHAR(10)  NOT NULL UNIQUE,
    name     VARCHAR(100) NOT NULL,
    city     VARCHAR(100) NOT NULL,
    currency CHAR(3)      NOT NULL
);

-- The catalogue is shared by all boutiques, so a product has no price and no stock.
CREATE TABLE product (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku         VARCHAR(30)  NOT NULL UNIQUE,
    name        VARCHAR(100) NOT NULL,
    description TEXT         NOT NULL,
    family      VARCHAR(30)  NOT NULL,
    size_ml     INT          NOT NULL CHECK (size_ml > 0)
);

-- What a boutique sells, at its local price, with its own stock.
-- No row means the product is not sold in that boutique.
-- CHECK (stock >= 0) is the last line of defence: the database refuses negative stock.
CREATE TABLE inventory (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    boutique_id BIGINT        NOT NULL REFERENCES boutique (id),
    product_id  BIGINT        NOT NULL REFERENCES product (id),
    price       NUMERIC(12,2) NOT NULL CHECK (price > 0),
    stock       INT           NOT NULL CHECK (stock >= 0),
    UNIQUE (boutique_id, product_id)
);

-- Everyone who has given an email, clients included.
-- Emails are stored in lower case so that one person cannot exist twice.
CREATE TABLE prospect (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email                  VARCHAR(254) NOT NULL UNIQUE CHECK (email = lower(email)),
    first_seen_boutique_id BIGINT       NOT NULL REFERENCES boutique (id),
    created_at             TIMESTAMPTZ  NOT NULL
);

-- A prospect becomes a client at their first completed order.
-- The primary key on prospect_id means a prospect can be converted only once,
-- and the foreign key means every client is also a prospect.
CREATE TABLE client (
    prospect_id  BIGINT      PRIMARY KEY REFERENCES prospect (id),
    converted_at TIMESTAMPTZ NOT NULL
);

-- "order" is a reserved word in SQL, hence "orders".
-- currency is copied from the boutique when the order is placed.
CREATE TABLE orders (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    boutique_id  BIGINT        NOT NULL REFERENCES boutique (id),
    prospect_id  BIGINT        NOT NULL REFERENCES prospect (id),
    status       VARCHAR(20)   NOT NULL CHECK (status IN ('PENDING', 'COMPLETED', 'CANCELLED')),
    currency     CHAR(3)       NOT NULL,
    total        NUMERIC(12,2) NOT NULL CHECK (total >= 0),
    created_at   TIMESTAMPTZ   NOT NULL,
    completed_at TIMESTAMPTZ,
    cancelled_at TIMESTAMPTZ,
    CHECK (status <> 'COMPLETED' OR completed_at IS NOT NULL),
    CHECK (status <> 'CANCELLED' OR cancelled_at IS NOT NULL)
);

CREATE INDEX idx_orders_boutique_status ON orders (boutique_id, status);

-- unit_price is a snapshot of the boutique price at the time of the order,
-- so later price changes do not rewrite past sales.
CREATE TABLE order_line (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id   BIGINT        NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
    product_id BIGINT        NOT NULL REFERENCES product (id),
    quantity   INT           NOT NULL CHECK (quantity > 0),
    unit_price NUMERIC(12,2) NOT NULL CHECK (unit_price > 0),
    line_total NUMERIC(12,2) NOT NULL CHECK (line_total > 0)
);

CREATE INDEX idx_order_line_order ON order_line (order_id);
